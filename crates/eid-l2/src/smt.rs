//! ЗАГОТОВКА (этап 12.1, агент A) — SMT-кодирование семантики #0.
//! Заполняется в ФАЗЕ 12.3 (за feature `smt = []`, кода за фичей пока НЕТ;
//! D4–D5 по §4 дока EID-L2-DESIGN v0.1).
//!
//! СПЕЦ (док EID-L2-DESIGN §4 «Кодирование #0 (Null) в SMT» и Приложение §3):
//!
//! Каждое значение Val кодируется кортежем:
//! ```text
//! SMT(v) = (is_null_v : Bool, num_v : Real)
//! ```
//!
//! §3.1 АКСИОМА НОРМАЛИЗАЦИИ КОНСТАНТ (Приложение дока):
//! * для `Expr::Null`:    is_null = true,  num = 0.0;
//! * для `Expr::Const(c)`: is_null = false, num = c;
//! * для неизвестной переменной #i: is_null_i и num_i свободны, но связаны
//!   ИНВАРИАНТОМ `is_null_i ⟹ (num_i == 0.0)` — благодаря ему внутри
//!   арифметических термов можно использовать num_i напрямую, без
//!   лишних ite(is_null_i, 0.0, val_i).
//!
//! §3.2 ТАБЛИЦА ТРАНСЛЯЦИИ ОПЕРАЦИЙ (Приложение дока; выборка —
//! реализовать ПОЛНОСТЬЮ по таблице при заполнении 12.3):
//! ```text
//! a + b  → is_null = false; num_a + num_b           (работает благодаря
//!                                                    инварианту is_null ⇒ num==0)
//! a - b  → num_a - num_b
//! a * b  → num_a * num_b
//! a / b  → num_a / num_b + проверка пути assert(num_b != 0.0)
//! a EQ b → (is_null_a && is_null_b)
//!          || (!is_null_a && !is_null_b && num_a == num_b)   // ТОЧНАЯ
//!          // формула дока: исключает ложные доказательства при
//!          // проверках IF [#1 EQ #0] (Null != 0.0!)
//! a NE b → !(a EQ b)
//! a GT b → num_a > num_b  (благодаря инварианту Null сравнивается как 0.0)
//! a LT b → num_a < num_b
//! a GE b → num_a >= num_b (автоматически даёт true для Null >= 0.0!)
//! a LE b → num_a <= num_b
//! G0 X(expr) → is_null_expr == true → координата X наследуется от
//!              prev_end.x; иначе → num_expr (слово игнорируется, таблица 2.1)
//! ```
//!
//! ОЖИДАЕМАЯ ТОЧКА ВХОДА (согласовать с 12.3 перед реализацией):
//! ```text
//! pub fn encode_val(v: Val) -> (bool, f64)  // инвариант is_null ⇒ num == 0.0
//! ```
//!
//! Референс семантики для зеркальности формул — `crate::eval`
