#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum DialectKind {
    #[serde(rename = "grbl-1.1")]
    Grbl11,
    GrblHal,
    #[serde(rename = "fluidnc")]
    FluidNc,
    #[serde(rename = "linuxcnc")]
    LinuxCnc,
    /// #25: Fanuc — имя валидно в профилях и CLI-словаре; адаптер eid-fanuc
    /// LIVE в registry (`translate::AnyAdapter::for_name("fanuc")` →
    /// обёртка `FanucNamedAdapter`, канон крейта — "fanuc-mill").
    #[serde(rename = "fanuc")]
    Fanuc,
    /// Этап 3 (agent C, регистрация "haas" по образцу #25/ff090bd): Haas —
    /// имя валидно в профилях и CLI-словаре; адаптер eid-haas LIVE в registry
    /// (`translate::AnyAdapter::for_name("haas")` → обёртка
    /// `HaasNamedAdapter`, канон крейта — "haas-mill").
    #[serde(rename = "haas")]
    Haas,
}

impl DialectKind {
    /// Каноническое имя диалекта (совпадает с TOML-представлением и
    /// `Adapter::dialect_name` для двух MVP-диалектов: "grbl-1.1", "linuxcnc").
    pub fn as_name(self) -> &'static str {
        match self {
            DialectKind::Grbl11 => "grbl-1.1",
            DialectKind::GrblHal => "grbl-hal",
            DialectKind::FluidNc => "fluidnc",
            DialectKind::LinuxCnc => "linuxcnc",
            DialectKind::Fanuc => "fanuc",
            DialectKind::Haas => "haas",
        }
    }

    /// Разбор канонического имени (обратен [`DialectKind::as_name`]).
    pub fn from_name(name: &str) -> Option<DialectKind> {
        match name {
            "grbl-1.1" => Some(DialectKind::Grbl11),
            "grbl-hal" => Some(DialectKind::GrblHal),
            "fluidnc" => Some(DialectKind::FluidNc),
            "linuxcnc" => Some(DialectKind::LinuxCnc),
            "fanuc" => Some(DialectKind::Fanuc),
            "haas" => Some(DialectKind::Haas),
            _ => None,
        }
    }
}

/// Пороги E_LIMIT_EXCEEDED — дефолты COVERAGE §1.2; профиль переопределяет.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct Limits {
    pub max_ops_per_program: usize,
    pub max_unroll_iterations: usize,
    pub max_source_lines: usize,
    pub max_word_chars: usize,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            max_ops_per_program: 200_000,
            max_unroll_iterations: 10_000,
            max_source_lines: 1_000_000,
            max_word_chars: 32,
        }
    }
}

/// Рабочий диапазон одной оси (станочные лимиты хода; structural-проверка
/// mock-сима, итерация 4). Единицы — единицы программы (mm/in не различаются
/// на этом уровне; профиль задаёт их для своего станка).
#[derive(Debug, Clone, Copy, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct AxisRange {
    pub min: f64,
    pub max: f64,
}

/// Пер-осевые лимиты хода станка. Опционально (дефолт — None: проверка
/// отключена); это НЕ retract_clearance (ruling SPEC: константа, не параметр
/// профиля — детерминизм) и не допуски эквивалентности (EQUIVALENCE §4).
#[derive(Debug, Clone, Copy, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct AxisLimits {
    pub x: AxisRange,
    pub y: AxisRange,
    pub z: AxisRange,
}

impl AxisLimits {
    /// Внутри диапазона по всем трём осям?
    pub fn contains(&self, x: f64, y: f64, z: f64) -> bool {
        let in_range = |r: &AxisRange, v: f64| r.min <= v && v <= r.max;
        in_range(&self.x, x) && in_range(&self.y, y) && in_range(&self.z, z)
    }
}

/// serde-обёртка для `Units` (eid_core::ast — замороженный тип БЕЗ
/// serde-derive, агент A; сериализация локальна для профиля: "mm" / "in").
/// eid-core не трогается (зона агента A).
mod units_serde {
    use eid_core::ast::Units;
    use serde::{Deserialize, Deserializer, Serializer};

    pub fn serialize<S: Serializer>(u: &Units, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(match u {
            Units::Mm => "mm",
            Units::In => "in",
        })
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<Units, D::Error> {
        let s = String::deserialize(d)?;
        match s.as_str() {
            "mm" => Ok(Units::Mm),
            "in" => Ok(Units::In),
            other => Err(serde::de::Error::custom(format!(
                "unknown units `{other}` (ожидается \"mm\" или \"in\")"
            ))),
        }
    }
}

fn default_axis_limits_units() -> Units {
    Units::Mm
}

/// Разумный верхний порог max_word_chars (#26): 1 байт — вырожденный, но
/// валидный; выше 4096 — конфигурационная ошибка, не лимит.
pub const MAX_WORD_CHARS_CAP: usize = 4096;

#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct MachineProfile {
    pub name: String,
    pub dialect: DialectKind,
    pub limits: Limits,
    /// R-эмиссия дуг — по флагу профиля с notice (EQUIVALENCE §4: по умолчанию
    /// всегда IJK; R1 всегда через IJK).
    pub emit_r_arcs: bool,
    /// #11: преамбула `(GENERATED BY EID — VERIFY IN SIMULATOR BEFORE
    /// MACHINING)` первой строкой выхода. Ставится ТОЛЬКО в integration-слое
    /// (`translate::translate_*_with_profile`); библиотечные `emit()` не
    /// меняются (золотовые R1-тексты байт-в-байт). Дефолт false (serde
    /// default — старые TOML валидны); комментарии эквивалентность не ломают.
    #[serde(default)]
    pub emit_preamble: bool,
    /// Пер-осевые лимиты хода станка (mock-sim, итерация 4); None = не заданы.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub axis_limits: Option<AxisLimits>,
    /// #27: единицы, в которых заданы `axis_limits` ("mm" | "in"; дефолт Mm).
    /// Если units программы (G20/G21 в AST-meta) != units профиля,
    /// `sim::check_program` масштабирует координаты ×25.4 / ÷25.4 перед
    /// сравнением с лимитами (станок физический — лимиты в единицах станка,
    /// программа может быть в inch).
    #[serde(default = "default_axis_limits_units", with = "units_serde")]
    pub axis_limits_units: Units,
}

impl MachineProfile {
    /// Загрузка профиля из TOML-файла (формат профиля — TOML, причина R-1:
    /// IMPLEMENTATION-PLAN §6 — serde_yaml в maintenance mode + unsafe-libyaml
    /// транзитивно; hand-parse — цель v1.0).
    ///
    /// Ошибка — `String` (замороженная сигнатура; отдельный `ProfileError`
    /// не вводится): чтение файла, парсинг TOML или пост-валидация семантики
    /// ([`MachineProfile::validate`], #26) не прошли.
    pub fn load(path: &Path) -> Result<MachineProfile, String> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("профиль {}: не удалось прочитать: {e}", path.display()))?;
        let profile: MachineProfile = toml::from_str(&text)
            .map_err(|e| format!("профиль {}: невалидный TOML: {e}", path.display()))?;
        profile
            .validate()
            .map_err(|e| format!("профиль {}: {e}", path.display()))?;
        Ok(profile)
    }

    /// Пост-валидация семантики (#26; TOML-парс ловит только форму):
    /// axis_limits — min <= max и конечные (is_finite) значения по всем осям;
    /// limits — рабочие пороги > 0, max_word_chars в разумном диапазоне
    /// 1..=[`MAX_WORD_CHARS_CAP`]. Ошибка — `String` с именем поля.
    pub fn validate(&self) -> Result<(), String> {
        if self.limits.max_ops_per_program == 0 {
            return Err("limits.max-ops-per-program должен быть > 0 (сейчас 0)".to_string());
        }
        if self.limits.max_unroll_iterations == 0 {
            return Err("limits.max-unroll-iterations должен быть > 0 (сейчас 0)".to_string());
        }
        if self.limits.max_source_lines == 0 {
            return Err("limits.max-source-lines должен быть > 0 (сейчас 0)".to_string());
        }
        if self.limits.max_word_chars == 0 {
            return Err("limits.max-word-chars должен быть >= 1 (сейчас 0)".to_string());
        }
        if self.limits.max_word_chars > MAX_WORD_CHARS_CAP {
            return Err(format!(
                "limits.max-word-chars вне разумного диапазона 1..={MAX_WORD_CHARS_CAP} (сейчас {})",
                self.limits.max_word_chars
            ));
        }
        if let Some(a) = &self.axis_limits {
            for (axis, r) in [("x", &a.x), ("y", &a.y), ("z", &a.z)] {
                for (bound, v) in [("min", r.min), ("max", r.max)] {
                    if !v.is_finite() {
                        return Err(format!(
                            "axis_limits.{axis}.{bound} = {v} — не конечное число (is_finite)"
                        ));
                    }
                }
                if r.min > r.max {
                    return Err(format!(
                        "axis_limits.{axis}: min ({}) > max ({})",
                        r.min, r.max
                    ));
                }
            }
        }
        Ok(())
    }

    /// Дефолтный профиль GRBL 1.1 (лимиты COVERAGE §1.2; emit_r_arcs: false —
    /// политика EQUIVALENCE §4). Сверяется с `GRBL_DEFAULT_PROFILE` тестом.
    pub fn grbl_default() -> Self {
        Self {
            name: "GRBL 1.1 default".to_string(),
            dialect: DialectKind::Grbl11,
            limits: Limits::default(),
            emit_r_arcs: false,
            emit_preamble: false,
            axis_limits: None,
            axis_limits_units: Units::Mm,
        }
    }

    /// Дефолтный профиль LinuxCNC (лимиты COVERAGE §1.2; emit_r_arcs: false —
    /// политика EQUIVALENCE §4). Сверяется с `LINUXCNC_DEFAULT_PROFILE` тестом.
    pub fn linuxcnc_default() -> Self {
        Self {
            name: "LinuxCNC default".to_string(),
            dialect: DialectKind::LinuxCnc,
            limits: Limits::default(),
            emit_r_arcs: false,
            emit_preamble: false,
            axis_limits: None,
            axis_limits_units: Units::Mm,
        }
    }

    /// Дефолтный профиль Fanuc (#25; лимиты COVERAGE §1.2). Диалект валиден
    /// для профилей и CLI; адаптер — live (см. `DialectKind::Fanuc`).
    /// Сверяется с `FANUC_DEFAULT_PROFILE` тестом.
    pub fn fanuc_default() -> Self {
        Self {
            name: "Fanuc default".to_string(),
            dialect: DialectKind::Fanuc,
            limits: Limits::default(),
            emit_r_arcs: false,
            emit_preamble: false,
            axis_limits: None,
            axis_limits_units: Units::Mm,
        }
    }

    /// Дефолтный профиль Haas (этап 3 agent C; лимиты COVERAGE §1.2).
    /// Диалект валиден для профилей и CLI; адаптер — live (см.
    /// `DialectKind::Haas`). Сверяется с `HAAS_DEFAULT_PROFILE` тестом.
    pub fn haas_default() -> Self {
        Self {
            name: "Haas default".to_string(),
            dialect: DialectKind::Haas,
            limits: Limits::default(),
            emit_r_arcs: false,
            emit_preamble: false,
            axis_limits: None,
            axis_limits_units: Units::Mm,
        }
    }

    /// Дефолтный профиль по каноническому имени диалекта (CLI #10: --profile
    /// не задан): семейство GRBL → grbl_default, fanuc → fanuc_default,
    /// haas → haas_default, остальные (linuxcnc; eid-l1 не DialectKind —
    /// лимиты те же) → linuxcnc_default.
    pub fn default_for_name(name: &str) -> Self {
        match DialectKind::from_name(name) {
            Some(DialectKind::LinuxCnc) => Self::linuxcnc_default(),
            Some(DialectKind::Fanuc) => Self::fanuc_default(),
            Some(DialectKind::Haas) => Self::haas_default(),
            Some(_) => Self::grbl_default(),
            None => Self::linuxcnc_default(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Обёртка: TOML-документ верхнего уровня обязан быть таблицей.
    #[derive(serde::Serialize, serde::Deserialize)]
    struct Wrap {
        d: DialectKind,
    }

    #[test]
    fn dialect_names_agree_with_serde() {
        let all = [
            (DialectKind::Grbl11, "grbl-1.1"),
            (DialectKind::GrblHal, "grbl-hal"),
            (DialectKind::FluidNc, "fluidnc"),
            (DialectKind::LinuxCnc, "linuxcnc"),
            (DialectKind::Fanuc, "fanuc"),
            // Этап 3 (agent C): регистрация "haas" — валидное имя.
            (DialectKind::Haas, "haas"),
        ];
        for (kind, name) in all {
            assert_eq!(kind.as_name(), name);
            assert_eq!(DialectKind::from_name(name), Some(kind));
            let ser = toml::to_string(&Wrap { d: kind }).unwrap();
            assert_eq!(ser.trim(), format!("d = \"{name}\""));
            let back: Wrap = toml::from_str(&format!("d = \"{name}\"")).unwrap();
            assert_eq!(back.d, kind);
        }
        assert_eq!(DialectKind::from_name("grbl"), None);
        assert_eq!(DialectKind::from_name("okuma"), None);
    }
}
