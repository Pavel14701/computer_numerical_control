// ProfileEmissionOpts (этап 8): эмиссионная проекция MachineProfile для
// проброса в адаптеры. Механика: trait Adapter v0.2 ЗАМОРОЖЕН — `emit(&self,
// program)` профиля не принимает (расширение trait = отдельное решение,
// молча не делается), поэтому опции хранит ОБЁРТКА registry
// (`translate::FanucNamedAdapter`/`HaasNamedAdapter`, конструктор
// `with_emission_opts`) и передаёт их крейт-функциям `emit_with_profile`.
// Grbl/LinuxCnc/EidText цели опции не получают (COVERAGE не объявляет для
// них этих флагов; guard диалекта — в translate.rs).
// ---------------------------------------------------------------------------

/// Эмиссионные опции профиля (этап 8): значения флагов fanuc/haas, влияющих
/// на байты эмиссии. Дефолт (`ProfileEmissionOpts::default()`) = текущее
/// поведение (до этапа 8).
#[derive(Debug, Clone, PartialEq)]
pub struct ProfileEmissionOpts {
    /// COVERAGE §5.1/§5.2 program_end: M30 (дефолт) | M02 — выбор профиля.
    pub program_end_style: ProgramEndStyle,
    /// R-дуги при эмиссии: false (дефолт) = всегда IJK; true = R-форма +
    /// notice на каждой R-дуге (полные круги 360° — всегда IJK, SPEC §6).
    pub allow_r_arcs: bool,
    /// Таблица соответствия расширенных WCS (fanuc: "G59.1" → "G54.1 P1";
    /// haas: "G59.1" → "G154 P1"); empty = выключена (текущее поведение).
    /// Формат значений уже проверен `MachineProfile::validate`.
    pub wcs_extended_map: std::collections::BTreeMap<String, String>,
}

impl Default for ProfileEmissionOpts {
    fn default() -> Self {
        Self {
            program_end_style: ProgramEndStyle::M30,
            allow_r_arcs: false,
            wcs_extended_map: std::collections::BTreeMap::new(),
        }
    }
}

impl ProfileEmissionOpts {
    /// Эмиссионная проекция профиля (`emit_r_arcs` v0.1 = `allow_r_arcs`).
    pub fn from_profile(p: &MachineProfile) -> Self {
        Self {
            program_end_style: p.program_end_style,
            allow_r_arcs: p.emit_r_arcs,
            wcs_extended_map: p.wcs_extended_map.clone().unwrap_or_default(),
        }
    }

    /// Все флаги в дефолтных значениях (= эмиссия до этапа 8, байт-в-байт)?
    pub fn is_default(&self) -> bool {
        *self == Self::default()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Обёртка: TOML-документ верхнего уровня обязан быть таблицей.
    #[derive(serde::Serialize, serde::Deserialize)]
    struct Wrap {
        d: DialectKind,
    }

    #[test]
    fn dialect_names_agree_with_serde() {
        let all = [
            (DialectKind::Grbl11, "grbl-1.1"),
            (DialectKind::GrblHal, "grbl-hal"),
            (DialectKind::FluidNc, "fluidnc"),
            (DialectKind::LinuxCnc, "linuxcnc"),
            (DialectKind::Fanuc, "fanuc"),
            // Этап 3 (agent C): регистрация "haas" — валидное имя.
            (DialectKind::Haas, "haas"),
        ];
        for (kind, name) in all {
            assert_eq!(kind.as_name(), name);
            assert_eq!(DialectKind::from_name(name), Some(kind));
            let ser = toml::to_string(&Wrap { d: kind }).unwrap();
            assert_eq!(ser.trim(), format!("d = \"{name}\""));
            let back: Wrap = toml::from_str(&format!("d = \"{name}\"")).unwrap();
            assert_eq!(back.d, kind);
        }
        assert_eq!(DialectKind::from_name("grbl"), None);
        assert_eq!(DialectKind::from_name("okuma"), None);
    }

    /// Этап 8: ProgramEndStyle — serde «M30»/«M02», дефолт M30, слова эмиссии.
    #[test]
    fn program_end_style_serde_and_words() {
        assert_eq!(ProgramEndStyle::default(), ProgramEndStyle::M30);
        assert_eq!(ProgramEndStyle::M30.word(), "M30");
        assert_eq!(ProgramEndStyle::M02.word(), "M02");
        // TOML-значение верхнего уровня — через обёртку (toml-крейт сериализует
        // только таблицы; паттерн Wrap из dialect-теста выше).
        #[derive(serde::Serialize, serde::Deserialize)]
        struct Wrap {
            s: ProgramEndStyle,
        }
        for (style, text) in [(ProgramEndStyle::M30, "M30"), (ProgramEndStyle::M02, "M02")] {
            let ser = toml::to_string(&Wrap { s: style }).unwrap();
            assert_eq!(ser.trim(), format!("s = \"{text}\""));
            let back: Wrap = toml::from_str(&format!("s = \"{text}\"")).unwrap();
            assert_eq!(back.s, style);
        }
        assert!(toml::from_str::<Wrap>("s = \"m30\"").is_err());
    }

    /// Этап 8: ProfileEmissionOpts — проекция профиля + is_default.
    #[test]
    fn emission_opts_projection_and_default() {
        assert!(ProfileEmissionOpts::default().is_default());
        let mut p = MachineProfile::fanuc_default();
        assert!(ProfileEmissionOpts::from_profile(&p).is_default());
        p.program_end_style = ProgramEndStyle::M02;
        p.emit_r_arcs = true;
        p.wcs_extended_map = Some(
            [("G59.1".to_string(), "G54.1 P1".to_string())]
                .into_iter()
                .collect(),
        );
        let o = ProfileEmissionOpts::from_profile(&p);
        assert!(!o.is_default());
        assert_eq!(o.program_end_style, ProgramEndStyle::M02);
        assert!(o.allow_r_arcs);
        assert_eq!(
            o.wcs_extended_map.get("G59.1").map(String::as_str),
            Some("G54.1 P1")
        );
    }
}
