/// Рабочий диапазон одной оси (станочные лимиты хода; structural-проверка
/// mock-сима, итерация 4). Единицы — единицы программы (mm/in не различаются
/// на этом уровне; профиль задаёт их для своего станка).
#[derive(Debug, Clone, Copy, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct AxisRange {
    pub min: f64,
    pub max: f64,
}

/// Пер-осевые лимиты хода станка. Опционально (дефолт — None: проверка
/// отключена); это НЕ retract_clearance (ruling SPEC: константа, не параметр
/// профиля — детерминизм) и не допуски эквивалентности (EQUIVALENCE §4).
#[derive(Debug, Clone, Copy, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub struct AxisLimits {
    pub x: AxisRange,
    pub y: AxisRange,
    pub z: AxisRange,
}

impl AxisLimits {
    /// Внутри диапазона по всем трём осям?
    pub fn contains(&self, x: f64, y: f64, z: f64) -> bool {
        let in_range = |r: &AxisRange, v: f64| r.min <= v && v <= r.max;
        in_range(&self.x, x) && in_range(&self.y, y) && in_range(&self.z, z)
    }
}

/// serde-обёртка для `Units` (eid_core::ast — замороженный тип БЕЗ
/// serde-derive, агент A; сериализация локальна для профиля: "mm" / "in").
/// eid-core не трогается (зона агента A).
mod units_serde {
    use eid_core::ast::Units;
    use serde::{Deserialize, Deserializer, Serializer};

    pub fn serialize<S: Serializer>(u: &Units, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(match u {
            Units::Mm => "mm",
            Units::In => "in",
        })
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<Units, D::Error> {
        let s = String::deserialize(d)?;
        match s.as_str() {
            "mm" => Ok(Units::Mm),
            "in" => Ok(Units::In),
            other => Err(serde::de::Error::custom(format!(
                "unknown units `{other}` (ожидается \"mm\" или \"in\")"
            ))),
        }
    }
}

fn default_axis_limits_units() -> Units {
    Units::Mm
}

