// ProfileEmissionOpts (этап 8): эмиссионная проекция MachineProfile для
// проброса в адаптеры. Механика: trait Adapter v0.2 ЗАМОРОЖЕН — `emit(&self,
// program)` профиля не принимает (расширение trait = отдельное решение,
// молча не делается), поэтому опции хранит ОБЁРТКА registry
// (`translate::FanucNamedAdapter`/`HaasNamedAdapter`, конструктор
// `with_emission_opts`) и передаёт их крейт-функциям `emit_with_profile`.
// Grbl/LinuxCnc/EidText цели опции не получают (COVERAGE не объявляет для
// них этих флагов; guard диалекта — в translate.rs).
// ---------------------------------------------------------------------------

/// Эмиссионные опции профиля (этап 8): значения флагов fanuc/haas, влияющих
/// на байты эмиссии. Дефолт (`ProfileEmissionOpts::default()`) = текущее
/// поведение (до этапа 8).
#[derive(Debug, Clone, PartialEq)]
pub struct ProfileEmissionOpts {
    /// COVERAGE §5.1/§5.2 program_end: M30 (дефолт) | M02 — выбор профиля.
    pub program_end_style: ProgramEndStyle,
    /// R-дуги при эмиссии: false (дефолт) = всегда IJK; true = R-форма +
    /// notice на каждой R-дуге (полные круги 360° — всегда IJK, SPEC §6).
    pub allow_r_arcs: bool,
    /// Таблица соответствия расширенных WCS (fanuc: "G59.1" → "G54.1 P1";
    /// haas: "G59.1" → "G154 P1"); empty = выключена (текущее поведение).
    /// Формат значений уже проверен `MachineProfile::validate`.
    pub wcs_extended_map: std::collections::BTreeMap<String, String>,
}

impl Default for ProfileEmissionOpts {
    fn default() -> Self {
        Self {
            program_end_style: ProgramEndStyle::M30,
            allow_r_arcs: false,
            wcs_extended_map: std::collections::BTreeMap::new(),
        }
    }
}

impl ProfileEmissionOpts {
    /// Эмиссионная проекция профиля (`emit_r_arcs` v0.1 = `allow_r_arcs`).
    pub fn from_profile(p: &MachineProfile) -> Self {
        Self {
            program_end_style: p.program_end_style,
            allow_r_arcs: p.emit_r_arcs,
            wcs_extended_map: p.wcs_extended_map.clone().unwrap_or_default(),
        }
    }

    /// Все флаги в дефолтных значениях (= эмиссия до этапа 8, байт-в-байт)?
    pub fn is_default(&self) -> bool {
        *self == Self::default()
    }
}

