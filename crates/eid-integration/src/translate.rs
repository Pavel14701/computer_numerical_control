/// Диагностика E_LIMIT_EXCEEDED конвейерной обвязки (формат зеркален
/// limit_err адаптеров: LimitInfo с порогом/фактом; stage — атрибуция этапа).
fn limit_diag(
    threshold: &'static str,
    threshold_value: usize,
    actual: f64,
    message: String,
    file: &str,
    line: u32,
    stage: Stage,
) -> Diagnostic {
    Diagnostic {
        stage,
        code: ErrorCode::LimitExceeded,
        message,
        src: Some(SrcSpan {
            file: file.into(),
            line_start: line,
            col_start: 1,
            line_end: line,
            col_end: 1,
        }),
        options: Vec::new(),
        limit: Some(LimitInfo {
            threshold,
            threshold_value: threshold_value as f64,
            actual,
        }),
    }
}

/// Строка кода без комментариев: `(...)` вырезаются (комментарии не вложены),
/// `;…` — до конца строки. Содержимое комментария заменяется пробелами
/// (границы токенов сохраняются). Грубая оценка достаточна: задача — поймать
/// слово длиннее порога ДО входа в лексер (guard зависания), не точный
/// лексический разбор — это делает адаптер диалекта.
fn strip_comments<'a>(line: &'a str, buf: &'a mut String) -> &'a str {
    buf.clear();
    let mut in_paren = false;
    for ch in line.chars() {
        match ch {
            '(' => {
                in_paren = true;
                buf.push(' ');
            }
            ')' => {
                in_paren = false;
                buf.push(' ');
            }
            ';' if !in_paren => break,
            _ if in_paren => buf.push(' '),
            c => buf.push(c),
        }
    }
    buf.as_str()
}

/// Текстовые guard'ы профиля ДО parse (лексер адаптера не должен висеть на
/// гигантском входе): max_source_lines (число строк) и max_word_chars
/// (длина слова — буква+значение; токены вне комментариев, консервативно
/// по whitespace-токенам: конкатенированный блок считается одним словом).
/// Отказ — `TranslateError::Parse` с E_LIMIT_EXCEEDED (Stage::Parse).
fn enforce_source_limits(src: &str, file: &str, limits: &Limits) -> Result<(), TranslateError> {
    let lines = src.lines().count();
    if lines > limits.max_source_lines {
        return Err(TranslateError::Parse(vec![limit_diag(
            "max_source_lines",
            limits.max_source_lines,
            lines as f64,
            format!("file has {lines} lines, limit {}", limits.max_source_lines),
            file,
            1,
            Stage::Parse,
        )]));
    }
    let mut buf = String::new();
    for (i, line) in src.lines().enumerate() {
        for tok in strip_comments(line, &mut buf).split_whitespace() {
            let is_word = matches!(tok.chars().next(), Some(c) if c.is_ascii_alphabetic());
            if is_word && tok.chars().count() > limits.max_word_chars {
                return Err(TranslateError::Parse(vec![limit_diag(
                    "max_word_chars",
                    limits.max_word_chars,
                    tok.chars().count() as f64,
                    format!(
                        "word value exceeds max_word_chars ({})",
                        limits.max_word_chars
                    ),
                    file,
                    (i + 1) as u32,
                    Stage::Parse,
                )]));
            }
        }
    }
    Ok(())
}

/// AST-пороги профиля ПОСЛЕ parse: max_ops_per_program (итоговый список опов)
/// и max_unroll_iterations — развёртка циклов видна снаружи как sub-индексы
/// (SPEC §11, 1-based): максимум sub = число РАЗВЁРНУТЫХ cycle-опов (та же
/// семантика, что у адаптерной est_total-защиты LinuxCNC, считающей итоговые
/// опы развёртки, а не литеральное L). Отказ — `TranslateError::Parse` с
/// E_LIMIT_EXCEEDED (Stage::Verify, как и limit_err адаптеров: проверка по
/// каноническому AST).
fn enforce_ast_limits(
    program: &Program,
    file: &str,
    limits: &Limits,
) -> Result<(), TranslateError> {
    let ops = program.ops.len();
    if ops > limits.max_ops_per_program {
        return Err(TranslateError::Parse(vec![limit_diag(
            "max_ops_per_program",
            limits.max_ops_per_program,
            ops as f64,
            format!(
                "program yields {ops} ops, limit {}",
                limits.max_ops_per_program
            ),
            file,
            1,
            Stage::Verify,
        )]));
    }
    let max_sub = program
        .ops
        .iter()
        .filter_map(|op| match op {
            Op::Rapid { sub: Some(s), .. }
            | Op::Linear { sub: Some(s), .. }
            | Op::Arc { sub: Some(s), .. }
            | Op::Dwell { sub: Some(s), .. } => Some(*s),
            _ => None,
        })
        .max();
    if let Some(s) = max_sub {
        // sub 1-based (SPEC §11): максимум = число развёрнутых cycle-опов.
        let expanded = s as usize;
        if expanded > limits.max_unroll_iterations {
            return Err(TranslateError::Parse(vec![limit_diag(
                "max_unroll_iterations",
                limits.max_unroll_iterations,
                expanded as f64,
                format!(
                    "cycle unroll yields {expanded} expanded ops, limit {}",
                    limits.max_unroll_iterations
                ),
                file,
                1,
                Stage::Verify,
            )]));
        }
    }
    Ok(())
}

/// Текст → текст: parse(источник) → RAW-правило → emit(цель). Профиль не
/// задан → дефолтный профиль диалекта (лимиты COVERAGE §1.2, преамбулы нет).
pub fn translate_text(
    from: &str,
    to: &str,
    src: &str,
    file: &str,
) -> Result<TranslateOutcome, TranslateError> {
    translate_text_with_profile(from, to, src, file, None)
}

/// Текст → текст с профилем станка (#2): лимиты профиля применяются конвейером
/// (`enforce_source_limits` до parse, `enforce_ast_limits` после), преамбула
/// (#11) — при `profile.emit_preamble`. Библиотечные emit() адаптеров не
/// меняются. `profile = None` → дефолтный профиль диалекта
/// (лимиты COVERAGE §1.2 у всех дефолтов совпадают, emit_preamble = false).
///
/// Этап 8: эмиссионные флаги профиля (program_end_style / wcs_extended_map /
/// emit_r_arcs = allow_r_arcs) пробрасываются в ЦЕЛЬ через обёртку registry
/// (`with_emission_opts`; trait Adapter v0.2 заморожен). Guard диалекта:
/// не-дефолтные флаги применимы только к цели своего диалекта — иначе отказ
/// E_INVALID_INPUT (тихое игнорирование флага профиля запрещено).
pub fn translate_text_with_profile(
    from: &str,
    to: &str,
    src: &str,
    file: &str,
    profile: Option<&MachineProfile>,
) -> Result<TranslateOutcome, TranslateError> {
    let default_limits = Limits::default();
    let limits = match profile {
        Some(p) => &p.limits,
        None => &default_limits,
    };
    let preamble = profile.is_some_and(|p| p.emit_preamble);

    // Текстовые guard'ы — до parse (guard зависания лексера, COVERAGE §1.2).
    enforce_source_limits(src, file, limits)?;

    let source = AnyAdapter::for_name(from)?;
    let target = AnyAdapter::for_name(to)?;

    // Этап 8: проброс эмиссионных опций в цель (fanuc/haas) + guard диалекта.
    let emission = profile.map(ProfileEmissionOpts::from_profile);
    if let (Some(p), Some(o)) = (profile, &emission) {
        if !o.is_default() && p.dialect.as_name() != target.name() {
            return Err(TranslateError::Emit(vec![Diagnostic {
                code: ErrorCode::InvalidInput,
                stage: Stage::Emit,
                src: None,
                options: Vec::new(),
                limit: None,
                message: format!(
                    "profile emission flags (program_end_style / wcs_extended_map / emit_r_arcs) объявлены для диалекта `{}`, но цель трансляции — `{}`: тихое игнорирование флага запрещено (флаги этапа 8 — fanuc/haas, COVERAGE §5.1/§5.2)",
                    p.dialect.as_name(),
                    target.name()
                ),
            }]));
        }
    }
    let target = target.with_emission_opts(emission);

    // 12.4-роут: макро-программа диалекта с L2-front-end → L2-конвейер
    // (parse Macro B/O-word → Pass-1 lower с кинематикой профиля →
    // L1-Program → emit цели). Ok(None) — чистый макро-фрагмент (lowering
    // дал ноль machine-опов: присваивания/циклы без ходов и program-end):
    // компилировать нечего, верное представление источника — L1-конвейер
    // ниже (same-dialect: verbatim-носители §8.1; кросс — честный
    // raw_refusal §8.2). Диалекты без front-end (grbl-1.1: словарь 1.1
    // макро-конструкций не содержит; eid-l1: канонический формат;
    // grbl-hal/fluidnc: pending) — тоже прежний конвейер (T1
    // zero-overhead: l2_available — один проход байтов по тексту).
    // L2-маршрут — ТОЛЬКО для макро-файлов (макро-маркеры помимо
    // ротационных слов): скомпилированный EID-выход (joints + штамп, без
    // макро-конструкций) идёт L1-маршрутом — L2-фронтенды модальные шапки
    // (G21/G90/G61…) несут носителями, что ломало бы реингест. l2_available
    // на одних A/B/C-словах — false-positive T1 (ротационные слова теперь
    // парсят сами L1-адаптеры — слоты).
    let l2_capable = eid_l2::l2_available(src)
        && has_macro_markers(src)
        && !has_nurbs_g5(src)
        && L2Frontend::of(source.name()).is_some();
    if l2_capable {
        match translate_l2_route(
            source.name(),
            &target,
            src,
            file,
            profile.map(|p| p.l2_lowering_config()).unwrap_or_default(),
            limits,
            preamble,
        ) {
            Ok(Some(outcome)) => return Ok(outcome),
            Ok(None) => {} // макро-фрагмент — L1-путь ниже
            Err(e) => return Err(e),
        }
    }

    let source_out = source.parse(src, file).map_err(TranslateError::Parse)?;
    let program = source_out.program;
    let notices = source_out.notices;

    // AST-пороги профиля — после parse (ops + развёртка sub-индексами).
    enforce_ast_limits(&program, file, limits)?;

    // RAW-правило (SPEC §8.2): кросс-диалект + Raw → отказ; same-dialect
    // machine-диалектов → plain emit (verbatim); golden/eid-l1-источник —
    // отказ любой цели (диалектно-нейтральный источник, B translate.rs).
    let spans = raw_spans(&program);
    let cross = target.dialect_name() != source.dialect_name();
    let golden = source.dialect_name() == EID_TEXT_DIALECT;
    if !spans.is_empty() && (cross || golden) {
        return Err(TranslateError::Emit(vec![raw_refusal(&spans)]));
    }

    // Геометрия L1-маршрута (ревью-6 + two-kins K1): штамп в источнике
    // говорит «значения — joints геометрии (параметры в штампе, hash —
    // integrity-пин)». Профиль с кинематикой описывает ЦЕЛЕВОЙ станок
    // (L1-адаптеры сами кинематику не применяют):
    //   * tampered/неразбираемый штамп → отказ (не молча-игнор);
    //   * hash совпал → pass-through 1:1 (уже joints цели);
    //   * hash различается, ТАГ тот же → **two-kins K1 transfer**:
    //     forward_штамп(joints) → TCP-pose → inverse_цель → новые joints
    //     (same-topology: семантика углов идентична, проходят насквозь;
    //     физическая инвариантность — forward_B(joints_B) ≡ forward_A(joints_A),
    //     проверяется тестом через ядро);
    //   * ТЕГ другой (кросс-топология) → честный отказ: семантика углов
    //     между семьями различна (стол↔голова — part-frame tool-axis solver
    //     per семью) — two-kins K2, named boundary, REPORT §16;
    //   * носители/дуги в программе при transfer → отказ (payload — кадры
    //     source-машины, геометрически непереносимы);
    //   * профиль Triv → цель не задана: pass-through, штамп форвардится
    //     (проверка неприменима — named в README).
    let src_stamp = match scan_kinematics_stamp(src) {
        Err(tamper) => {
            return Err(TranslateError::Emit(vec![Diagnostic {
                code: ErrorCode::InvalidInput,
                stage: Stage::Emit,
                src: None,
                options: Vec::new(),
                limit: None,
                message: tamper,
            }]));
        }
        Ok(other) => other,
    };
    let mut program = program;
    let mut stamp_head: Option<String> = None;
    if let Some((src_mode, src_hash)) = &src_stamp {
        let target_mode = profile
            .map(|p| p.kinematics.to_rtcp_mode())
            .unwrap_or(RtcpMode::Off);
        let target_hash = target_mode.geometry_hash();
        match (&target_hash, &src_hash.as_str()) {
            (Some(want), h) if want == h => {
                // Совпал: 1:1, штамп форвардится (геометрия штампа источника).
                stamp_head = Some(format!(
                    "(EID KINEMATICS: {} hash={src_hash} {} — xyz/rotary values are machine joints for this geometry only)",
                    kins_tag(src_mode),
                    stamp_tail(src_mode)
                ));
            }
            (Some(_), _) if kins_tag(src_mode) == kins_tag(&target_mode) => {
                // K1 two-kins: same-topology different-geometry — TRANSFER.
                let transferred = two_kins_same_topology(
                    std::mem::take(&mut program.ops),
                    src_mode,
                    &target_mode,
                )
                .map_err(|msg| {
                    TranslateError::Emit(vec![Diagnostic {
                        code: ErrorCode::InvalidInput,
                        stage: Stage::Emit,
                        src: None,
                        options: Vec::new(),
                        limit: None,
                        message: msg,
                    }])
                })?;
                program.ops = transferred;
                stamp_head = Some(format!(
                    "(EID KINEMATICS: {} hash={} {} — xyz/rotary values are machine joints for this geometry only; transferred from {} hash={src_hash})",
                    kins_tag(&target_mode),
                    target_hash.unwrap(),
                    stamp_tail(&target_mode),
                    kins_tag(src_mode)
                ));
            }
            (Some(_), _) => {
                return Err(TranslateError::Emit(vec![Diagnostic {
                    code: ErrorCode::InvalidInput,
                    stage: Stage::Emit,
                    src: None,
                    options: Vec::new(),
                    limit: None,
                    message: format!(
                        "cross-topology transfer not supported: источник joints \
                         для {} (hash={src_hash}), профиль цели — {} — семантика \
                         углов между семьями различна (стол↔голова: part-frame \
                         tool-axis solver per семью); two-kins K2 — named boundary, \
                         REPORT §16",
                        kins_tag(src_mode),
                        kins_tag(&target_mode)
                    ),
                }]));
            }
            (None, _) => {
                // Triv-цель: машина цели не задана — pass-through, штамп живёт.
                stamp_head = Some(format!(
                    "(EID KINEMATICS: {} hash={src_hash} {} — xyz/rotary values are machine joints for this geometry only)",
                    kins_tag(src_mode),
                    stamp_tail(src_mode)
                ));
            }
        }
    }

    let target_out = target.emit(&program).map_err(TranslateError::Emit)?;
    // #11: преамбулу ставит ТОЛЬКО integration-слой (emit() адаптеров не
    // меняются — золотовые R1-тексты байт-в-байт; комментарий семантику не
    // меняет — EQUIVALENCE игнорирует комментарии). Штамп геометрии
    // форвардится (маркер живёт через хопы пайплайна).
    let mut head = String::new();
    if preamble {
        head.push_str(GENERATED_PREAMBLE);
        head.push('\n');
    }
    if let Some(stamp_line) = &stamp_head {
        head.push_str(stamp_line);
        head.push('\n');
    }
    let emitted = format!("{head}{}", target_out.text);
    let emit_warnings = target_out.diagnostics;
    let q3_warnings = target_out.warnings;

    Ok(TranslateOutcome {
        from: source.name().to_string(),
        to: target.name().to_string(),
        program,
        emitted,
        notices,
        emit_warnings,
        q3_warnings,
        l2_lowering_diagnostics: Vec::new(),
    })
}

// ---------------------------------------------------------------------------
// Two-kins K1 (same-topology different-geometry): op-level pass.
// Контракт (решение ревью-7): forward_штамп → TCP-pose → inverse_цель —
// углы проходят насквозь (same-tag: семантика углов идентична), xyz и
// слоты переписываются. Носители/дуги — отказ (payload геометрически
// непереносим). Кросс-топология — K2 (named), сюда не попадает.
// ---------------------------------------------------------------------------

/// Джоинты топологии → Pose6 (неиспользуемые оси = 0.0).
fn kins_forward_pose(mode: &RtcpMode, j: &Pose6) -> Pose6 {
    use eid_l2::kinematics::{xyzac_forward, xyzbc_forward, Joints5, JointsBC};
    use eid_l2::kinematics_5axis::{fiveaxis_forward, JointsXyzbcw};
    use eid_l2::kinematics_maxkins::{maxkins_forward, JointsMaxkins};
    use eid_l2::kinematics_tdr::{tdr_forward, JointsTdr};
    use eid_l2::kinematics_trsrn::{trsrn_tcp_forward, JointsTsrn};
    match mode {
        RtcpMode::Off => *j,
        RtcpMode::XyzacTrt { params } => {
            xyzac_forward(params, &Joints5::new(j.x, j.y, j.z, j.a, j.c))
        }
        RtcpMode::XyzbcTrt { params } => {
            xyzbc_forward(params, &JointsBC::new(j.x, j.y, j.z, j.b, j.c))
        }
        RtcpMode::XyzabTdr { params } => {
            tdr_forward(params, &JointsTdr::new(j.x, j.y, j.z, j.a, j.b))
        }
        RtcpMode::Trsrn { params } => {
            trsrn_tcp_forward(params, &JointsTsrn::new(j.x, j.y, j.z, j.a, j.b, j.c))
        }
        RtcpMode::Maxkins { params } => {
            let pose = maxkins_forward(
                params,
                &JointsMaxkins {
                    x: j.x,
                    y: j.y,
                    z: j.z,
                    a: j.a,
                    b: j.b,
                    c: j.c,
                    u: 0.0,
                    v: 0.0,
                    w: 0.0,
                },
            );
            Pose6::new(pose.x, pose.y, pose.z, pose.a, pose.b, pose.c)
        }
        RtcpMode::FiveAxis { params } => {
            let pose = fiveaxis_forward(
                params,
                &JointsXyzbcw {
                    x: j.x,
                    y: j.y,
                    z: j.z,
                    b: j.b,
                    c: j.c,
                    w: 0.0,
                },
            );
            Pose6::new(pose.x, pose.y, pose.z, 0.0, pose.b, pose.c)
        }
    }
}

/// TCP-pose → джоинты целевой топологии → Pose6 (неиспользуемые оси = 0.0).
fn kins_inverse_pose(mode: &RtcpMode, pose: &Pose6) -> Pose6 {
    use eid_l2::kinematics::{xyzac_inverse, xyzbc_inverse};
    use eid_l2::kinematics_5axis::{fiveaxis_inverse, PoseXyzbcw};
    use eid_l2::kinematics_maxkins::{maxkins_inverse, PoseMaxkins};
    use eid_l2::kinematics_tdr::tdr_inverse;
    use eid_l2::kinematics_trsrn::trsrn_tcp_inverse;
    match mode {
        RtcpMode::Off => *pose,
        RtcpMode::XyzacTrt { params } => {
            let j = xyzac_inverse(params, pose);
            Pose6::new(j.x, j.y, j.z, j.a, 0.0, j.c)
        }
        RtcpMode::XyzbcTrt { params } => {
            let j = xyzbc_inverse(params, pose);
            Pose6::new(j.x, j.y, j.z, 0.0, j.b, j.c)
        }
        RtcpMode::XyzabTdr { params } => {
            let j = tdr_inverse(params, pose);
            Pose6::new(j.x, j.y, j.z, j.a, j.b, 0.0)
        }
        RtcpMode::Trsrn { params } => {
            let j = trsrn_tcp_inverse(params, pose);
            Pose6::new(j.x, j.y, j.z, j.a, j.b, j.c)
        }
        RtcpMode::Maxkins { params } => {
            let j = maxkins_inverse(
                params,
                &PoseMaxkins {
                    x: pose.x,
                    y: pose.y,
                    z: pose.z,
                    a: pose.a,
                    b: pose.b,
                    c: pose.c,
                    u: 0.0,
                    v: 0.0,
                    w: 0.0,
                },
            );
            Pose6::new(j.x, j.y, j.z, j.a, j.b, j.c)
        }
        RtcpMode::FiveAxis { params } => {
            let j = fiveaxis_inverse(
                params,
                &PoseXyzbcw {
                    x: pose.x,
                    y: pose.y,
                    z: pose.z,
                    b: pose.b,
                    c: pose.c,
                    w: 0.0,
                },
            );
            Pose6::new(j.x, j.y, j.z, 0.0, j.b, j.c)
        }
    }
}

/// Точка (xyz + слоты) под two-kins: forward_штамп → inverse_цель; слоты
/// переписываются ТОЛЬКО у установленных (Some — resolved-значение, None —
/// угол не установлен в программе — остаётся None: машина цели тоже home).
fn two_kins_point(p: &Point3, src: &RtcpMode, dst: &RtcpMode) -> Point3 {
    let j = Pose6::new(
        p.x.value(),
        p.y.value(),
        p.z.value(),
        p.a.as_ref().map(|n| n.value()).unwrap_or(0.0),
        p.b.as_ref().map(|n| n.value()).unwrap_or(0.0),
        p.c.as_ref().map(|n| n.value()).unwrap_or(0.0),
    );
    let pose = kins_forward_pose(src, &j);
    let joints = kins_inverse_pose(dst, &pose);
    let num = |v: f64| Num::new(eid_core::emitter::fmt_num(v), v);
    let slot = |was: &Option<Num>, v: f64| was.as_ref().map(|_| num(v));
    Point3::pose(
        num(joints.x),
        num(joints.y),
        num(joints.z),
        slot(&p.a, joints.a),
        slot(&p.b, joints.b),
        slot(&p.c, joints.c),
    )
}

/// Two-kins K1 pass: same-topology different-geometry. Носители/дуги —
/// отказ (payload — кадры source-машины, геометрически непереносим;
/// named: «сегментируйте источник»).
fn two_kins_same_topology(ops: Vec<Op>, src: &RtcpMode, dst: &RtcpMode) -> Result<Vec<Op>, String> {
    ops.into_iter()
        .map(|op| match op {
            Op::Rapid {
                start,
                end,
                state,
                src: op_src,
                sub,
            } => {
                let start = match start {
                    StartPoint::Known(p) => StartPoint::Known(two_kins_point(&p, src, dst)),
                    StartPoint::Unknown => StartPoint::Unknown,
                };
                Ok(Op::Rapid {
                    start,
                    end: two_kins_point(&end, src, dst),
                    state,
                    src: op_src,
                    sub,
                })
            }
            Op::Linear {
                start,
                end,
                state,
                src: op_src,
                sub,
            } => {
                let start = match start {
                    StartPoint::Known(p) => StartPoint::Known(two_kins_point(&p, src, dst)),
                    StartPoint::Unknown => StartPoint::Unknown,
                };
                Ok(Op::Linear {
                    start,
                    end: two_kins_point(&end, src, dst),
                    state,
                    src: op_src,
                    sub,
                })
            }
            Op::Arc { .. } => Err(
                "cross-geometry transfer: дуга (ARC) геометрически непереносима \
                 без пересечения TCP-пути в joint-полилинию (tolerance-решение, \
                 named boundary) — сегментируйте источник на линейные ходы"
                    .to_string(),
            ),
            Op::Raw { .. } => Err(
                "cross-geometry transfer: RAW-носитель в программе — payload \
                 содержит кадры source-машины (ротационные дуги/state-only), \
                 геометрически непереносим (named boundary — REPORT §16)"
                    .to_string(),
            ),
            other => Ok(other),
        })
        .collect()
}

/// Файл → файл (CLI-путь, критерий #9): чтение, конвейер, запись. Профиль не
/// задан → дефолтный профиль диалекта (см. [`translate_text`]).
pub fn translate_file(
    from: &str,
    to: &str,
    input: &Path,
    output: &Path,
) -> Result<TranslateOutcome, TranslateError> {
    translate_file_with_profile(from, to, input, output, None)
}

/// Файл → файл с профилем станка (#2): лимиты профиля конвейером, преамбула
/// #11 — при `profile.emit_preamble` (первая строка выходного .ngc).
pub fn translate_file_with_profile(
    from: &str,
    to: &str,
    input: &Path,
    output: &Path,
    profile: Option<&MachineProfile>,
) -> Result<TranslateOutcome, TranslateError> {
    let src = std::fs::read_to_string(input)
        .map_err(|e| TranslateError::Io(format!("input {}: {e}", input.display())))?;
    let file_name = input
        .file_name()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| input.display().to_string());
    let outcome = translate_text_with_profile(from, to, &src, &file_name, profile)?;
    std::fs::write(output, &outcome.emitted)
        .map_err(|e| TranslateError::Io(format!("output {}: {e}", output.display())))?;
    Ok(outcome)
}

/// Разбор текста конкретным диалектом (verify, e2e).
pub fn parse_with(dialect: &str, src: &str, file: &str) -> Result<Program, TranslateError> {
    let adapter = AnyAdapter::for_name(dialect)?;
    let out = adapter.parse(src, file).map_err(TranslateError::Parse)?;
    Ok(out.program)
}
