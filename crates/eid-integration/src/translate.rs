/// Обёртка registry: конкретный адаптер + буферы notices/warnings
/// (trait v0.1 не имеет канала для Ok-диагностик; буферы — паттерн адаптеров).
pub enum AnyAdapter {
    Grbl(GrblAdapter),
    LinuxCnc(LinuxCncAdapter),
    Fanuc(FanucNamedAdapter),
    Haas(HaasNamedAdapter),
    EidText(eid_core::adapter::EidTextAdapter),
}

impl AnyAdapter {
    /// Registry по каноническому имени диалекта ("grbl-1.1", "linuxcnc",
    /// "fanuc", "haas", "eid-l1"); алиас "grbl" = "grbl-1.1" (CLI, критерий
    /// #9). "fanuc" — live (#25, [`FanucNamedAdapter`]); "haas" — live
    /// (eid-haas этапы 1–3 готовы, регистр [`HaasNamedAdapter`]); pending
    /// остаются только grbl-hal/fluidnc.
    pub fn for_name(name: &str) -> Result<AnyAdapter, TranslateError> {
        match name {
            "grbl-1.1" | "grbl" => Ok(AnyAdapter::Grbl(GrblAdapter::new())),
            "linuxcnc" => Ok(AnyAdapter::LinuxCnc(LinuxCncAdapter::new())),
            "fanuc" => Ok(AnyAdapter::Fanuc(FanucNamedAdapter::new())),
            "haas" => Ok(AnyAdapter::Haas(HaasNamedAdapter::new())),
            "eid-l1" => Ok(AnyAdapter::EidText(eid_core::adapter::EidTextAdapter::new())),
            "grbl-hal" | "fluidnc" => Err(TranslateError::AdapterPending {
                dialect: name.to_string(),
                message: "adapter pending (C iteration 4+: семейство GRBL); доступно: grbl-1.1, linuxcnc, fanuc, haas, eid-l1".to_string(),
            }),
            other => Err(TranslateError::UnknownDialect(other.to_string())),
        }
    }

    /// Имя диалекта адаптера (как `Adapter::dialect_name`).
    pub fn name(&self) -> &'static str {
        self.as_adapter().dialect_name()
    }

    /// Этап 8: присоединить профильные эмиссионные опции. Механика проброса:
    /// trait Adapter v0.2 ЗАМОРОЖЕН — `emit(&self, program)` профиль не
    /// принимает (расширение trait = отдельное решение, молча не делается),
    /// поэтому опции хранит ОБЁРТКА registry
    /// (`FanucNamedAdapter`/`HaasNamedAdapter`, поле `emission_opts` +
    /// `emit_with_opts` адаптера крейта). Цели grbl/linuxcnc/eid-l1 опции
    /// не получают (COVERAGE не объявляет для них этих флагов; guard
    /// диалекта — в `translate_text_with_profile`).
    pub fn with_emission_opts(self, opts: Option<ProfileEmissionOpts>) -> Self {
        match self {
            AnyAdapter::Fanuc(mut a) => {
                a.emission_opts = opts;
                AnyAdapter::Fanuc(a)
            }
            AnyAdapter::Haas(mut a) => {
                a.emission_opts = opts;
                AnyAdapter::Haas(a)
            }
            other => other,
        }
    }

    fn as_adapter(&self) -> &dyn Adapter {
        match self {
            AnyAdapter::Grbl(a) => a,
            AnyAdapter::LinuxCnc(a) => a,
            AnyAdapter::Fanuc(a) => a,
            AnyAdapter::Haas(a) => a,
            AnyAdapter::EidText(a) => a,
        }
    }

    // v0.2 #22 (INTERFACE-V0.2-DESIGN §2.2): take_notices/take_emit_
    // diagnostics/take_q3_warnings-троица УДАЛЕНА — parse/emit возвращают
    // owning-результат (ParseOutput/EmitOutput); тройка «notices =
    // Vec<String> через format!» заменена типизированным Vec<core Notice>
    // с Display (`{kind:?}: {message} (op {op_index})` — формат строк
    // сохранён 1:1).
}

