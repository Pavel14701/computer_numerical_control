/// Все Raw-спаны AST (порядок опов).
fn raw_spans(program: &Program) -> Vec<SrcSpan> {
    program
        .ops
        .iter()
        .filter_map(|o| match o {
            Op::Raw { src, .. } => Some(src.clone()),
            _ => None,
        })
        .collect()
}

