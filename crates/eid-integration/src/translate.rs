/// Диагностика E_LIMIT_EXCEEDED конвейерной обвязки (формат зеркален
/// limit_err адаптеров: LimitInfo с порогом/фактом; stage — атрибуция этапа).
fn limit_diag(
    threshold: &'static str,
    threshold_value: usize,
    actual: f64,
    message: String,
    file: &str,
    line: u32,
    stage: Stage,
) -> Diagnostic {
    Diagnostic {
        stage,
        code: ErrorCode::LimitExceeded,
        message,
        src: Some(SrcSpan {
            file: file.into(),
            line_start: line,
            col_start: 1,
            line_end: line,
            col_end: 1,
        }),
        options: Vec::new(),
        limit: Some(LimitInfo {
            threshold,
            threshold_value: threshold_value as f64,
            actual,
        }),
    }
}

/// Строка кода без комментариев: `(...)` вырезаются (комментарии не вложены),
/// `;…` — до конца строки. Содержимое комментария заменяется пробелами
/// (границы токенов сохраняются). Грубая оценка достаточна: задача — поймать
/// слово длиннее порога ДО входа в лексер (guard зависания), не точный
/// лексический разбор — это делает адаптер диалекта.
fn strip_comments<'a>(line: &'a str, buf: &'a mut String) -> &'a str {
    buf.clear();
    let mut in_paren = false;
    for ch in line.chars() {
        match ch {
            '(' => {
                in_paren = true;
                buf.push(' ');
            }
            ')' => {
                in_paren = false;
                buf.push(' ');
            }
            ';' if !in_paren => break,
            _ if in_paren => buf.push(' '),
            c => buf.push(c),
        }
    }
    buf.as_str()
}

/// Текстовые guard'ы профиля ДО parse (лексер адаптера не должен висеть на
/// гигантском входе): max_source_lines (число строк) и max_word_chars
/// (длина слова — буква+значение; токены вне комментариев, консервативно
/// по whitespace-токенам: конкатенированный блок считается одним словом).
/// Отказ — `TranslateError::Parse` с E_LIMIT_EXCEEDED (Stage::Parse).
fn enforce_source_limits(src: &str, file: &str, limits: &Limits) -> Result<(), TranslateError> {
    let lines = src.lines().count();
    if lines > limits.max_source_lines {
        return Err(TranslateError::Parse(vec![limit_diag(
            "max_source_lines",
            limits.max_source_lines,
            lines as f64,
            format!("file has {lines} lines, limit {}", limits.max_source_lines),
            file,
            1,
            Stage::Parse,
        )]));
    }
    let mut buf = String::new();
    for (i, line) in src.lines().enumerate() {
        for tok in strip_comments(line, &mut buf).split_whitespace() {
            let is_word = matches!(tok.chars().next(), Some(c) if c.is_ascii_alphabetic());
            if is_word && tok.chars().count() > limits.max_word_chars {
                return Err(TranslateError::Parse(vec![limit_diag(
                    "max_word_chars",
                    limits.max_word_chars,
                    tok.chars().count() as f64,
                    format!(
                        "word value exceeds max_word_chars ({})",
                        limits.max_word_chars
                    ),
                    file,
                    (i + 1) as u32,
                    Stage::Parse,
                )]));
            }
        }
    }
    Ok(())
}

/// AST-пороги профиля ПОСЛЕ parse: max_ops_per_program (итоговый список опов)
/// и max_unroll_iterations — развёртка циклов видна снаружи как sub-индексы
/// (SPEC §11, 1-based): максимум sub = число РАЗВЁРНУТЫХ cycle-опов (та же
/// семантика, что у адаптерной est_total-защиты LinuxCNC, считающей итоговые
/// опы развёртки, а не литеральное L). Отказ — `TranslateError::Parse` с
/// E_LIMIT_EXCEEDED (Stage::Verify, как и limit_err адаптеров: проверка по
/// каноническому AST).
fn enforce_ast_limits(
    program: &Program,
    file: &str,
    limits: &Limits,
) -> Result<(), TranslateError> {
    let ops = program.ops.len();
    if ops > limits.max_ops_per_program {
        return Err(TranslateError::Parse(vec![limit_diag(
            "max_ops_per_program",
            limits.max_ops_per_program,
            ops as f64,
            format!(
                "program yields {ops} ops, limit {}",
                limits.max_ops_per_program
            ),
            file,
            1,
            Stage::Verify,
        )]));
    }
    let max_sub = program
        .ops
        .iter()
        .filter_map(|op| match op {
            Op::Rapid { sub: Some(s), .. }
            | Op::Linear { sub: Some(s), .. }
            | Op::Arc { sub: Some(s), .. }
            | Op::Dwell { sub: Some(s), .. } => Some(*s),
            _ => None,
        })
        .max();
    if let Some(s) = max_sub {
        // sub 1-based (SPEC §11): максимум = число развёрнутых cycle-опов.
        let expanded = s as usize;
        if expanded > limits.max_unroll_iterations {
            return Err(TranslateError::Parse(vec![limit_diag(
                "max_unroll_iterations",
                limits.max_unroll_iterations,
                expanded as f64,
                format!(
                    "cycle unroll yields {expanded} expanded ops, limit {}",
                    limits.max_unroll_iterations
                ),
                file,
                1,
                Stage::Verify,
            )]));
        }
    }
    Ok(())
}

/// Текст → текст: parse(источник) → RAW-правило → emit(цель). Профиль не
/// задан → дефолтный профиль диалекта (лимиты COVERAGE §1.2, преамбулы нет).
pub fn translate_text(
    from: &str,
    to: &str,
    src: &str,
    file: &str,
) -> Result<TranslateOutcome, TranslateError> {
    translate_text_with_profile(from, to, src, file, None)
}

/// Текст → текст с профилем станка (#2): лимиты профиля применяются конвейером
/// (`enforce_source_limits` до parse, `enforce_ast_limits` после), преамбула
/// (#11) — при `profile.emit_preamble`. Библиотечные emit() адаптеров не
/// меняются. `profile = None` → дефолтный профиль диалекта
/// (лимиты COVERAGE §1.2 у всех дефолтов совпадают, emit_preamble = false).
///
/// Этап 8: эмиссионные флаги профиля (program_end_style / wcs_extended_map /
/// emit_r_arcs = allow_r_arcs) пробрасываются в ЦЕЛЬ через обёртку registry
/// (`with_emission_opts`; trait Adapter v0.2 заморожен). Guard диалекта:
/// не-дефолтные флаги применимы только к цели своего диалекта — иначе отказ
/// E_INVALID_INPUT (тихое игнорирование флага профиля запрещено).
pub fn translate_text_with_profile(
    from: &str,
    to: &str,
    src: &str,
    file: &str,
    profile: Option<&MachineProfile>,
) -> Result<TranslateOutcome, TranslateError> {
    let default_limits = Limits::default();
    let limits = match profile {
        Some(p) => &p.limits,
        None => &default_limits,
    };
    let preamble = profile.is_some_and(|p| p.emit_preamble);

    // Текстовые guard'ы — до parse (guard зависания лексера, COVERAGE §1.2).
    enforce_source_limits(src, file, limits)?;

    let source = AnyAdapter::for_name(from)?;
    let target = AnyAdapter::for_name(to)?;

    // Этап 8: проброс эмиссионных опций в цель (fanuc/haas) + guard диалекта.
    let emission = profile.map(ProfileEmissionOpts::from_profile);
    if let (Some(p), Some(o)) = (profile, &emission) {
        if !o.is_default() && p.dialect.as_name() != target.name() {
            return Err(TranslateError::Emit(vec![Diagnostic {
                code: ErrorCode::InvalidInput,
                stage: Stage::Emit,
                src: None,
                options: Vec::new(),
                limit: None,
                message: format!(
                    "profile emission flags (program_end_style / wcs_extended_map / emit_r_arcs) объявлены для диалекта `{}`, но цель трансляции — `{}`: тихое игнорирование флага запрещено (флаги этапа 8 — fanuc/haas, COVERAGE §5.1/§5.2)",
                    p.dialect.as_name(),
                    target.name()
                ),
            }]));
        }
    }
    let target = target.with_emission_opts(emission);

    let source_out = source.parse(src, file).map_err(TranslateError::Parse)?;
    let program = source_out.program;
    let notices = source_out.notices;

    // AST-пороги профиля — после parse (ops + развёртка sub-индексами).
    enforce_ast_limits(&program, file, limits)?;

    // RAW-правило (SPEC §8.2): кросс-диалект + Raw → отказ; same-dialect
    // machine-диалектов → plain emit (verbatim); golden/eid-l1-источник —
    // отказ любой цели (диалектно-нейтральный источник, B translate.rs).
    let spans = raw_spans(&program);
    let cross = target.dialect_name() != source.dialect_name();
    let golden = source.dialect_name() == EID_TEXT_DIALECT;
    if !spans.is_empty() && (cross || golden) {
        return Err(TranslateError::Emit(vec![raw_refusal(&spans)]));
    }

    let target_out = target.emit(&program).map_err(TranslateError::Emit)?;
    // #11: преамбулу ставит ТОЛЬКО integration-слой (emit() адаптеров не
    // меняются — золотовые R1-тексты байт-в-байт; комментарий семантику не
    // меняет — EQUIVALENCE игнорирует комментарии).
    let emitted = if preamble {
        format!("{GENERATED_PREAMBLE}\n{}", target_out.text)
    } else {
        target_out.text
    };
    let emit_warnings = target_out.diagnostics;
    let q3_warnings = target_out.warnings;

    Ok(TranslateOutcome {
        from: source.name().to_string(),
        to: target.name().to_string(),
        program,
        emitted,
        notices,
        emit_warnings,
        q3_warnings,
    })
}

/// Файл → файл (CLI-путь, критерий #9): чтение, конвейер, запись. Профиль не
/// задан → дефолтный профиль диалекта (см. [`translate_text`]).
pub fn translate_file(
    from: &str,
    to: &str,
    input: &Path,
    output: &Path,
) -> Result<TranslateOutcome, TranslateError> {
    translate_file_with_profile(from, to, input, output, None)
}

/// Файл → файл с профилем станка (#2): лимиты профиля конвейером, преамбула
/// #11 — при `profile.emit_preamble` (первая строка выходного .ngc).
pub fn translate_file_with_profile(
    from: &str,
    to: &str,
    input: &Path,
    output: &Path,
    profile: Option<&MachineProfile>,
) -> Result<TranslateOutcome, TranslateError> {
    let src = std::fs::read_to_string(input)
        .map_err(|e| TranslateError::Io(format!("input {}: {e}", input.display())))?;
    let file_name = input
        .file_name()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| input.display().to_string());
    let outcome = translate_text_with_profile(from, to, &src, &file_name, profile)?;
    std::fs::write(output, &outcome.emitted)
        .map_err(|e| TranslateError::Io(format!("output {}: {e}", output.display())))?;
    Ok(outcome)
}

/// Разбор текста конкретным диалектом (verify, e2e).
pub fn parse_with(dialect: &str, src: &str, file: &str) -> Result<Program, TranslateError> {
    let adapter = AnyAdapter::for_name(dialect)?;
    let out = adapter.parse(src, file).map_err(TranslateError::Parse)?;
    Ok(out.program)
}
