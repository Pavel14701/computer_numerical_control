/// Обойти все G-коды текста (комментарии вырезаны общим strip_comments;
/// o<name>/o123-токены пропущены — имя `o<g20sub>` не G-код; слова
/// разбираются парами (буква, число) — «G90G21»/«N10G20» видятся; числа
/// с хвостовой точкой «G21.» нормализуются trim_end_matches('.')).
/// Читатель каждого кода — `hit` (ранний выход — возврат false).
fn scan_g_codes(src: &str, buf: &mut String, mut hit: impl FnMut(f64) -> bool) {
    for line in src.lines() {
        for tok in strip_comments(line, buf).split_whitespace() {
            let up = tok.to_ascii_uppercase();
            if up.starts_with('O') {
                continue; // O-заголовки/имена подпрограмм — не слова G
            }
            let bytes = up.as_bytes();
            let mut i = 0;
            while i < bytes.len() {
                let letter = bytes[i];
                i += 1;
                let start = i;
                while i < bytes.len() && (bytes[i].is_ascii_digit() || bytes[i] == b'.') {
                    i += 1;
                }
                if start == i || letter != b'G' {
                    continue;
                }
                let text = up[start..i].trim_end_matches('.');
                if let Ok(g) = text.parse::<f64>() {
                    if !hit(g) {
                        return;
                    }
                }
            }
        }
    }
}

/// NURBS-гейт маршрута (SPEC v0.19): файлы с G5/G5.1/G5.2/G5.3 идут
/// ЧИСТЫМ L1-конвейером — у linuxcnc-адаптера есть spline_active-режим
/// line-level Raw{SEM} (корень ревизии v0.19: строки-продолжения NURBS
/// без G-кода; L2-парсер их НЕ знает и трактует как модальные ходы —
/// маршрут L2 регрессировал бы v0.19). Гейт консервативен по диалектам:
/// G5-семья в fanuc/haas тоже уводит файл в L1-путь (zero regression).
fn has_nurbs_g5(src: &str) -> bool {
    let mut buf = String::new();
    let mut nurbs = false;
    scan_g_codes(src, &mut buf, |g| {
        if matches!(g, g if g == 5.0 || g == 5.1 || g == 5.2 || g == 5.3) {
            nurbs = true;
            false // ранний выход
        } else {
            true
        }
    });
    nurbs
}

/// Скан G20/G21 в тексте L2-источника. НУЖЕН потому, что L2-парсеры
/// абсорбируют единицы молча (ABSORB_G на Move-кадрах; автономная
/// модальная строка «G21 G90» — modal-only, мимо AST): единицы в
/// L2-Program не попадают, а эмиссия пишет шапку G20|G21 из
/// `Program.units` — молчаливо-неверная шапка = ошибка ×25.4 в станочных
/// координатах (см. [`scan_g_codes`] — механика токенов).
fn scan_l2_units(src: &str) -> L2UnitsScan {
    let mut buf = String::new();
    let mut saw_g20 = false;
    let mut saw_g21 = false;
    scan_g_codes(src, &mut buf, |g| {
        match g {
            20.0 => saw_g20 = true,
            21.0 => saw_g21 = true,
            _ => {}
        }
        !(saw_g20 && saw_g21) // Mixed известен — ранний выход
    });
    match (saw_g20, saw_g21) {
        (true, true) => L2UnitsScan::Mixed,
        (true, false) => L2UnitsScan::In,
        _ => L2UnitsScan::Mm,
    }
}

/// Декод payload_hex носителя (hex UTF-8 байтов кадра, кодирование
/// `raw_frame_op` eid-l2) → текст кадра. Повреждённый hex → честный
/// плейсхолдер (не panic — эмиссия не должна падать на данных).
fn decode_hex_payload(hex: &str) -> String {
    let bytes = (0..hex.len() / 2)
        .filter_map(|i| u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16).ok())
        .collect::<Vec<u8>>();
    String::from_utf8_lossy(&bytes).into_owned()
}

/// Маркер геометрии в исходном тексте (штамп lowering'а с активной
/// кинематикой). Комментарий — контроллеры и semantic_diff его игнорируют;
/// конвейер читает как ПОЛНОЕ описание геометрии, для которой посчитаны
/// joint-значения:
/// `(EID KINEMATICS: <tag> hash=<16hex> <params…>)`.
/// Параметры в штампе обязательны (ревью-7): hash — только идентичность,
/// для two-kins forward нужен сам TrtParams; hash — integrity-пин
/// (параметры пересчитываются в hash; случайная порча → отказ;
/// осознанная подмена параметров+hash вместе — не детектируется, named).
const KINEMATICS_STAMP_PREFIX: &str = "(EID KINEMATICS:";

/// Канонический тег топологии (совпадает с TOML-именем MachineKinematics).
fn kins_tag(mode: &RtcpMode) -> &'static str {
    match mode {
        RtcpMode::Off => "off",
        RtcpMode::XyzacTrt { .. } => "xyzac-trt",
        RtcpMode::XyzbcTrt { .. } => "xyzbc-trt",
        RtcpMode::XyzabTdr { .. } => "xyzab-tdr",
        RtcpMode::Trsrn { .. } => "trsrn",
        RtcpMode::Maxkins { .. } => "maxkins",
        RtcpMode::FiveAxis { .. } => "five-axis",
    }
}

/// Хвост штампа — сериализация параметров геометрии (f64 через Display —
/// Ryū short-round-trip: parse восстанавливает биты точно).
fn stamp_tail(mode: &RtcpMode) -> String {
    let f = |v: f64| format!("{v}");
    match mode {
        RtcpMode::Off => String::new(),
        RtcpMode::XyzacTrt { params } | RtcpMode::XyzbcTrt { params } => format!(
            "rot-point={},{},{} y-offset={} x-offset={} z-offset={} con={}",
            f(params.rot_point[0]),
            f(params.rot_point[1]),
            f(params.rot_point[2]),
            f(params.y_offset),
            f(params.x_offset),
            f(params.z_offset),
            params.conventional
        ),
        RtcpMode::XyzabTdr { params } => format!(
            "rot-point={},{},{} x-offset={} z-offset={} tool-offset-z={}",
            f(params.rot_point[0]),
            f(params.rot_point[1]),
            f(params.rot_point[2]),
            f(params.x_offset),
            f(params.z_offset),
            f(params.tool_offset_z)
        ),
        RtcpMode::Trsrn { params } => format!(
            "nut-angle={} y-pivot={} z-pivot={} x-offset={} y-offset={} \
             y-rot-axis={} z-rot-axis={} tool-offset-z={}",
            f(params.nut_angle),
            f(params.y_pivot),
            f(params.z_pivot),
            f(params.x_offset),
            f(params.y_offset),
            f(params.y_rot_axis),
            f(params.z_rot_axis),
            f(params.tool_offset_z)
        ),
        RtcpMode::Maxkins { params } => format!(
            "pivot-length={} tool-length={} con={}",
            f(params.pivot_length),
            f(params.tool_length),
            params.conventional
        ),
        RtcpMode::FiveAxis { params } => format!(
            "pivot-length={} tool-length={}",
            f(params.pivot_length),
            f(params.tool_length)
        ),
    }
}

/// Реконструкция RtcpMode из тега + kv-хвоста штампа. None — неизвестный
/// тег/битые поля (вызывающая сторона отказывает — неразбираемый штамп
/// не молча игнорируется).
fn mode_from_stamp(tag: &str, kv: &str) -> Option<RtcpMode> {
    let get = |key: &str| -> Option<f64> {
        kv.split_whitespace().find_map(|tok| {
            tok.strip_prefix(key)
                .and_then(|rest| rest.strip_prefix('='))
                .and_then(|v| v.parse::<f64>().ok())
        })
    };
    let get_bool = |key: &str| -> Option<bool> {
        kv.split_whitespace().find_map(|tok| {
            tok.strip_prefix(key)
                .and_then(|rest| rest.strip_prefix('='))
                .and_then(|v| match v {
                    "true" => Some(true),
                    "false" => Some(false),
                    _ => None,
                })
        })
    };
    let point = |key: &str| -> Option<[f64; 3]> {
        let tok = kv
            .split_whitespace()
            .find(|t| t.starts_with(key))?
            .strip_prefix(key)?
            .strip_prefix('=')?;
        let mut it = tok.split(',');
        Some([
            it.next()?.parse().ok()?,
            it.next()?.parse().ok()?,
            it.next()?.parse().ok()?,
        ])
    };
    match tag {
        "xyzac-trt" | "xyzbc-trt" => {
            let params = TrtParams::new(
                point("rot-point")?,
                get("y-offset")?,
                get("x-offset")?,
                get("z-offset")?,
                get_bool("con")?,
            );
            Some(if tag == "xyzac-trt" {
                RtcpMode::XyzacTrt { params }
            } else {
                RtcpMode::XyzbcTrt { params }
            })
        }
        "xyzab-tdr" => Some(RtcpMode::XyzabTdr {
            params: TdrParams::new(
                point("rot-point")?,
                get("x-offset")?,
                get("z-offset")?,
                get("tool-offset-z")?,
            ),
        }),
        "trsrn" => Some(RtcpMode::Trsrn {
            params: TrsrnParams {
                nut_angle: get("nut-angle")?,
                y_pivot: get("y-pivot")?,
                z_pivot: get("z-pivot")?,
                x_offset: get("x-offset")?,
                y_offset: get("y-offset")?,
                y_rot_axis: get("y-rot-axis")?,
                z_rot_axis: get("z-rot-axis")?,
                tool_offset_z: get("tool-offset-z")?,
            },
        }),
        "maxkins" => Some(RtcpMode::Maxkins {
            params: MaxkinsParams {
                pivot_length: get("pivot-length")?,
                tool_length: get("tool-length")?,
                conventional: get_bool("con")?,
            },
        }),
        "five-axis" => Some(RtcpMode::FiveAxis {
            params: FiveAxisParams {
                pivot_length: get("pivot-length")?,
                tool_length: get("tool-length")?,
            },
        }),
        _ => None,
    }
}

/// Скан штампа с integrity-пином: Ok(Some((mode, hash))) — валидный штамп
/// (параметры пересчитаны в hash — совпал); Ok(None) — штампа нет; Err —
/// штамп есть, но неразбираем/подменён (честный отказ, не молча-игнор).
fn scan_kinematics_stamp(src: &str) -> Result<Option<(RtcpMode, String)>, String> {
    // Первый штамп в тексте (все пути внутри возвращают — цикл не нужен).
    if let Some(i) = src.find(KINEMATICS_STAMP_PREFIX) {
        let start = i + KINEMATICS_STAMP_PREFIX.len();
        let end = start + src[start..].find(')').unwrap_or(src.len() - start);
        let inner = src[start..end].trim();
        let mut toks = inner.split_whitespace();
        let tag = toks.next().unwrap_or("").to_string();
        let hash = toks
            .find_map(|t| t.strip_prefix("hash="))
            .unwrap_or("")
            .to_string();
        let tail = inner
            .find("hash=")
            .map(|k| {
                let rest = &inner[k..];
                // пропустить hash=xxxx до whitespace
                let after = rest.find(' ').map(|s| &rest[s..]).unwrap_or("");
                after.trim().to_string()
            })
            .unwrap_or_default();
        if hash.len() != 16 {
            return Err(format!(
                "kinematics stamp unparsable: «{inner}» (hash= 16 hex)"
            ));
        }
        let Some(mode) = mode_from_stamp(&tag, &tail) else {
            return Err(format!(
                "kinematics stamp unparsable: tag `{tag}` неизвестен или параметры битые"
            ));
        };
        if mode.geometry_hash().as_deref() != Some(hash.as_str()) {
            return Err(format!(
                "kinematics stamp tampered: параметры дают hash={}, штамп заявляет hash={hash} \
                 (integrity-пин; случайная порча — перекомпилируйте источник)",
                mode.geometry_hash().unwrap_or_default()
            ));
        }
        return Ok(Some((mode, hash)));
    }
    Ok(None)
}

/// Есть ли в тексте МАКРО-маркеры помимо ротационных слов (♯, O-word+keyword,
/// IF/WHILE/GOTO, G65/G66, трансформации, RTCP)? НУЖЕН для роутинга: скомпилированный
/// EID-выход (joints + штамп) не макро-файл — его L2-фронтенд-парсеры
/// модальные шапки (G21/G90/G61…) несут носителями; верный маршрут таких
/// файлов — L1-адаптеры (слоты парсят сами). l2_available-эвристика T1
/// триггерится на одних A/B/C-словах — false-positive, который теперь
/// различается явно.
fn has_macro_markers(src: &str) -> bool {
    let stripped = {
        let mut out = String::with_capacity(src.len());
        let mut in_paren = false;
        let mut in_line = false;
        for ch in src.chars() {
            match ch {
                ';' if !in_paren => in_line = true,
                '(' if !in_line => in_paren = true,
                ')' => in_paren = false,
                '\n' => {
                    in_paren = false;
                    in_line = false;
                    out.push(' ');
                }
                c if !in_paren && !in_line => out.push(c),
                _ => {}
            }
        }
        out
    };
    if stripped.contains('#') {
        return true;
    }
    for tok in stripped.split_whitespace() {
        let up = tok.to_ascii_uppercase();
        if matches!(
            up.as_str(),
            "IF" | "WHILE"
                | "GOTO"
                | "G65"
                | "G66"
                | "G67"
                | "G68"
                | "G68.1"
                | "G68.2"
                | "G68.3"
                | "G51"
                | "G51.1"
                | "G50.1"
                | "G43.4"
                | "G43.5"
                | "G31"
        ) {
            return true;
        }
        if up.len() >= 2
            && up.as_bytes()[0] == b'O'
            && (up.as_bytes()[1] == b'<' || up.as_bytes()[1..].iter().all(|c| c.is_ascii_digit()))
        {
            return true; // O-word (o<имя> или o123) — макро-конструкция
        }
    }
    false
}

/// L2-конвейер (12.4-роут): front-end parse → Pass-1 lower
/// ([`L2Config`] — RTCP-режим из kinematics профиля) → сборка L1-Program →
/// общий хвост конвейера (AST-лимиты → RAW-правило → emit цели).
///
/// Сборка Program: `eid_version` — magic «EID/L1 v0.3» (SPEC §10.4, эмиттеры
/// отвергают прочие); `units` — units-скан текста (G20/G21 в AST не
/// попадают — см. [`scan_l2_units`]; ОБА кода → отказ
/// E_UNSUPPORTED_SEMANTICS: units-switch конвертируется только анкер-механизмом
/// L1-адаптера linuxcnc, у lowering механизма нет); `path_mode` — ExactPath
/// (G61/G64 L2-парсеры абсорбируют; канонический выбор грамматик адаптеров —
/// blend-толеранс макро-программы не переносится, emission-предупреждения
/// целей активны); `frame_preset` — None (G54–G59 абсорбируются; чтение
/// offset-ов через SysVar::WcsOffset честно требует таблицу станка —
/// E_REQUIRES_MACHINE_TABLE). Порядок опов —
/// [`eid_l2::interp::LoweringResult::into_ordered_ops`] (носители МЕЖДУ
/// ходами; конкатенация l1_ops ++ raw_tail переупорядочила бы программу).
/// RTCP-маркеры (G43.4/G43.5/G49-носители pass-1) под активной кинематикой
/// материализуются комментариями шапки (исполняемая эмиссия G43.4 на цель =
/// двойное преобразование — см. шаг 4 в теле); авто-PEND — зеркало
/// L1-канонизаторов (SPEC §3 v0.16).
///
/// Возвращает `Ok(None)` для чистого макро-фрагмента (ноль machine-опов —
/// источник вернётся L1-конвейеру).
fn translate_l2_route(
    source_name: &str,
    target: &AnyAdapter,
    src: &str,
    file: &str,
    mut cfg: L2Config,
    limits: &Limits,
    preamble: bool,
) -> Result<Option<TranslateOutcome>, TranslateError> {
    let frontend = L2Frontend::of(source_name).expect("роут вызывается только при front-end");

    // 1. units-скан ДО parse: Mixed = честный отказ (молча-неверная шапка
    //    эмиссии запрещена — та же дисциплина «тихое игнорирование», что и
    //    в emission-флагах профиля).
    let units = match scan_l2_units(src) {
        L2UnitsScan::Mm => Units::Mm,
        L2UnitsScan::In => Units::In,
        L2UnitsScan::Mixed => {
            return Err(TranslateError::Parse(vec![Diagnostic {
                code: ErrorCode::UnsupportedSemantics,
                stage: Stage::Parse,
                src: None,
                options: Vec::new(),
                limit: None,
                message: "units-switch (G20 и G21 в одной программе) не переносится \
                          L2-конвейером: L2-парсеры абсорбируют единицы, lowering не \
                          конвертирует координаты (анкер-механизм — только L1-адаптер \
                          linuxcnc); маршрут L2 отклонён"
                    .to_string(),
            }]));
        }
    };

    // 2. Front-end parse (Macro B / O-word RS274).
    let l2prog = frontend.parse(src).map_err(|errs| {
        TranslateError::Parse(
            errs.iter()
                .map(|e| Diagnostic {
                    code: e.error_code(),
                    stage: Stage::Parse,
                    src: None,
                    options: Vec::new(),
                    limit: None,
                    message: format!("L2 {}: {}", frontend.dialect(), e.message()),
                })
                .collect(),
        )
    })?;

    // 2б. (СНЯТО — L1 v0.4, SPEC v0.22) Гейт ротационных ходов: L1-грамматика
    //     получила resolved rotary-слоты Point3 (a/b/c) — pass-through/solver
    //     углы представимы, ходы с ротационными словами понижаются end-to-end
    //     (trt/tdr/maxkins/5axis — программные углы pass-through; trsrn —
    //     solver-углы; Off — pass-through). Честные остаточные границы:
    //     дуги с ротационными словами — носители lowering (§6), цели без осей
    //     в словаре (grbl) — emit-гейт legality (E_UNSUPPORTED_SYNTAX).
    let kins_active = cfg.rtcp_mode != eid_l2::interp::RtcpMode::Off;

    // 2в. ЗАЩИТА ГЕОМЕТРИИ (ревью-6, `kinematics_hash`): joint-значения —
    //     специфика геометрии профиля, которым они посчитаны. Маркер
    //     `(EID KINEMATICS: … hash=…)` в источнике (штамп прежнего lowering)
    //     делает геометрию ЯВНОЙ:
    //     * hash совпал → значения УЖЕ joints этой геометрии; повторный
    //       inverse = двойное преобразование → lowering форсируется в
    //       Off (pass-through: реэмиссия того же joint-потока);
    //     * hash НЕ совпал → честный отказ (кросс-геометрия без пересчёта =
    //       тихая порча траектории; two-kins — named boundary, REPORT §16);
    //     * маркера нет → lowering применяется как TCP-семантика (обычный
    //       цеховой файл — ответственность пользователя, named в README);
    //     Выход штампуется тем же hash (идемпотентно: штамп живёт через хопы
    //       пайплайна EID). Под Off-профилем (Triv) hash не проверяется и
    //       не ставится — геометрия не применялась.
    let mut stamp: Option<String> = None; // готовая строка штампа
    if kins_active {
        let name = cfg.rtcp_mode.name();
        let hash = cfg
            .rtcp_mode
            .geometry_hash()
            .expect("kins_active ⇒ режим с геометрией");
        match scan_kinematics_stamp(src) {
            Err(tamper) => {
                return Err(TranslateError::Parse(vec![Diagnostic {
                    code: ErrorCode::InvalidInput,
                    stage: Stage::Parse,
                    src: None,
                    options: Vec::new(),
                    limit: None,
                    message: tamper,
                }]))
            }
            Ok(Some((_, src_hash))) => {
                if src_hash != hash {
                    // Макро-файл со штампом чужой геометрии — неоднозначный
                    // гибрид (TCP-семантика vs уже-joints): K1-transfer здесь
                    // не делается (см. L1-маршрут), честный отказ.
                    return Err(TranslateError::Parse(vec![Diagnostic {
                        code: ErrorCode::InvalidInput,
                        stage: Stage::Parse,
                        src: None,
                        options: Vec::new(),
                        limit: None,
                        message: format!(
                            "geometry hash mismatch: источник скомпилирован для \
                             кинематики hash={src_hash}, активный профиль даёт \
                             hash={hash} ({name}) — макро-файл со штампом чужой \
                             геометрии неоднозначен (TCP-семантика или уже-joints); \
                             cross-geometry transfer выполняется на plain-файлах \
                             через L1-маршрут (two-kins K1, REPORT §16)"
                        ),
                    }]));
                }
                // Совпал: значения уже joints этой геометрии — pass-through.
                cfg.rtcp_mode = eid_l2::interp::RtcpMode::Off;
            }
            Ok(None) => {}
        }
        stamp = Some(format!(
            "(EID KINEMATICS: {} hash={hash} {} — xyz/rotary values are machine joints for this geometry only)",
            kins_tag(&cfg.rtcp_mode),
            stamp_tail(&cfg.rtcp_mode)
        ));
    } else {
        // Off-профиль: tampered штамп всё равно отказ (не молча-игнор),
        // валидный — форвардится в выход.
        match scan_kinematics_stamp(src) {
            Err(tamper) => {
                return Err(TranslateError::Parse(vec![Diagnostic {
                    code: ErrorCode::InvalidInput,
                    stage: Stage::Parse,
                    src: None,
                    options: Vec::new(),
                    limit: None,
                    message: tamper,
                }]))
            }
            Ok(Some((src_mode, src_hash))) => {
                stamp = Some(format!(
                    "(EID KINEMATICS: {} hash={src_hash} {} — xyz/rotary values are machine joints for this geometry only)",
                    kins_tag(&src_mode),
                    stamp_tail(&src_mode)
                ));
            }
            Ok(None) => {}
        }
    }

    // 3. Pass-1 lowering (бюджеты L2Config; RTCP-режим — из профиля или
    //    форсированный Off при hash-совпадении).
    //    cfg потребляется lower().
    let mut res = eid_l2::lowering::lower(&l2prog, cfg).map_err(|e| {
        TranslateError::Parse(vec![Diagnostic {
            code: e.error_code(),
            stage: Stage::Canonicalize,
            src: None,
            options: Vec::new(),
            limit: None,
            message: e.message(),
        }])
    })?;
    let mut l2_diags = std::mem::take(&mut res.diagnostics);

    // 4. Сборка L1-Program (см. контракт в doc функции). НОЛЬ machine-опов
    //    = чистый макро-фрагмент (присваивания/циклы, ни ходов, ни конца
    //    программы): L2-компиляции нечего — Ok(None) вернет источник
    //    L1-конвейеру (same-dialect verbatim-носители; кросс — raw_refusal).
    //
    //    RTCP-маркеры pass-1 (носители с reason «L2 pass-1 [rtcp]:» — кадры
    //    G43.4/G43.5/G49): под АКТИВНОЙ кинематикой (rtcp_mode != Off)
    //    ходы ПОСЛЕ маркера уже resolved в machine-оси веткой 2.5 lowering
    //    — маркер не untranslated-контент, а отчёт компилятора. Исполняемая
    //    эмиссия G43.4 на цель ЗАПРЕЩЕНА: цель применила бы свою кинематику
    //    ПОВЕРХ наших joints (двойное преобразование — неверная траектория).
    //    Маркер материализуется комментарием в шапке выхода + диагностикой
    //    («не молча») и НЕ участвует в RAW-правиле §8.2. Под Off (Triv)
    //    компиляции не было — маркер остаётся Raw-носителем (прежнее
    //    поведение: same-dialect verbatim G43.4 делает ходы TCP на цели).
    let mut rtcp_marker_notes: Vec<String> = Vec::new();
    let mut ops: Vec<Op> = Vec::new();
    for op in res.into_ordered_ops() {
        if kins_active {
            if let Op::Raw {
                reason,
                payload_hex,
                src,
                ..
            } = &op
            {
                if reason.starts_with("L2 pass-1 [rtcp]:") {
                    let frame = decode_hex_payload(payload_hex);
                    rtcp_marker_notes.push(frame.trim().to_string());
                    l2_diags.push(Diagnostic {
                        code: ErrorCode::UnsupportedSemantics,
                        stage: Stage::Canonicalize,
                        src: Some(src.clone()),
                        options: Vec::new(),
                        limit: None,
                        message: format!(
                            "RTCP-маркер materialized as comment (ходы после него \
                             resolved в machine-оси кинематикой профиля; исполняемая \
                             эмиссия G43.4/G49 на цель = двойное преобразование): \
                             «{}»",
                            frame.trim()
                        ),
                    });
                    continue;
                }
            }
        }
        ops.push(op);
    }
    if ops.is_empty() {
        return Ok(None);
    }
    // SPEC §3 v0.16 (зеркало L1-канонизаторов): отсутствие M2/M30 в
    // lowered-потоке — неявный конец, авто-PEND последним опом; «не молча» —
    // диагностика в l2_lowering_diagnostics (аналог NoticeKind::
    // MissingProgramEnd).
    if !ops.iter().any(|o| matches!(o, Op::ProgramEnd { .. })) {
        let line_count = src.lines().count().max(1) as u32;
        ops.push(Op::ProgramEnd {
            src: SrcSpan {
                file: file.into(),
                line_start: line_count,
                col_start: 1,
                line_end: line_count,
                col_end: 1,
            },
        });
        l2_diags.push(Diagnostic {
            code: ErrorCode::UnsupportedSemantics,
            stage: Stage::Canonicalize,
            src: None,
            options: Vec::new(),
            limit: None,
            message: "W_MISSING_PROGRAM_END: no M2/M30 in lowered stream — implicit \
                      program end appended (SPEC §3 v0.16, зеркало L1-канонизаторов)"
                .to_string(),
        });
    }
    let program = Program {
        eid_version: "EID/L1 v0.3".to_string(),
        units,
        path_mode: PathMode::ExactPath,
        frame_preset: None,
        ops,
    };

    // 5. Общий хвост: AST-лимиты профиля → RAW-правило (SPEC §8.2) → emit.
    enforce_ast_limits(&program, file, limits)?;
    let spans = raw_spans(&program);
    let cross = target.dialect_name() != source_name;
    let golden = source_name == EID_TEXT_DIALECT;
    if !spans.is_empty() && (cross || golden) {
        return Err(TranslateError::Emit(vec![raw_refusal(&spans)]));
    }
    let target_out = target.emit(&program).map_err(TranslateError::Emit)?;
    // Шапка выхода: преамбула #11 + RTCP-комментарии компиляции (в порядке
    // кадров-маркеров; текст кадра verbatim в комментарии).
    let mut head = String::new();
    if preamble {
        head.push_str(GENERATED_PREAMBLE);
        head.push('\n');
    }
    // Штамп геометрии (ревью-6): joint-значения потока валидны только для
    // геометрии hash — идемпотентный маркер для следующего хопа EID-пайплайна
    // (совпадение → pass-through; расхождение → честный отказ). Контроллеры
    // и semantic_diff комментарии игнорируют.
    if let Some(line) = &stamp {
        head.push_str(line);
        head.push('\n');
    }
    for note in &rtcp_marker_notes {
        head.push_str(&format!(
            "(EID RTCP COMPILED: {note} — motion in machine axes)\n"
        ));
    }
    let emitted = format!("{head}{}", target_out.text);

    Ok(Some(TranslateOutcome {
        from: source_name.to_string(),
        to: target.name().to_string(),
        program,
        emitted,
        notices: Vec::new(),
        emit_warnings: target_out.diagnostics,
        q3_warnings: target_out.warnings,
        l2_lowering_diagnostics: l2_diags,
    }))
}

