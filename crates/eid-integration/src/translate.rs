//! translate — live-конвейер CLI (итерация 4): registry адаптеров диалектов +
//! parse(источник) → emit(цель). Реализует критерий MVP #9/#10 (demo round-trip).
//!
//! RAW-правило (SPEC §8.2, итерация 5 — фикс критический): AST с Raw-опом
//! отказывает кросс-диалектной цели (`E_RAW_UNTRANSLATABLE`, все Raw-спаны в
//! `options`, первый в `src`); same-dialect — plain emit (verbatim RAW
//! легален, §8.1); golden/eid-l1-источник — любой Raw отказывает любой цели.
//! Формат диагностики — eid_core::diag::raw_refusal (аудит #7: прежняя
//! зеркальная копия eid-harness::translate::raw_refusal устранена — единая
//! точка в core; дрейф более невозможен).
//!
//! Реальные адаптеры: GrblAdapter / LinuxCncAdapter / FanucNamedAdapter
//! ("fanuc", eid-fanuc) / EidTextAdapter (eid-l1) — вызываются через trait
//! object (`&dyn Adapter`, freeze v0.1). grbl-hal/fluidnc — pending (Агент C,
//! семейство GRBL). Профиль станка: сигнатуры Adapter (v0.1, заморожены) профиль не
//! принимают, поэтому лимиты профиля применяются КОНВЕЙЕРНОЙ обвязкой
//! (`*_with_profile`, аудит #2): max_source_lines/max_word_chars — до parse
//! (guard зависания лексера), max_ops_per_program и max_unroll_iterations —
//! после parse по AST (sub-индексы развёртки, SPEC §11); вызовы без профиля —
//! дефолтный профиль диалекта (лимиты COVERAGE §1.2). Диагностика —
//! E_LIMIT_EXCEEDED с LimitInfo (формат зеркален limit_err адаптеров). Внутренние
//! константные пороги адаптеров остаются как нижняя защита: профиль может
//! УСТРОЖИТЬ лимит, но поднять выше адаптерного не может (расхождение
//! зафиксировано: trait v0.1 не прокидывает конфиг в адаптер).
//!
//! Префамбул #11: при `MachineProfile::emit_preamble = true` к эмиссии
//! добавляется первой строкой `(GENERATED BY EID — VERIFY IN SIMULATOR BEFORE
//! MACHINING)` — ТОЛЬКО здесь (integration-слой); библиотечные `emit()` не
//! меняются (золотовые R1-тексты байт-в-байт). Комментарии эквивалентность
//! не меняют (semantic_diff их не видит).

